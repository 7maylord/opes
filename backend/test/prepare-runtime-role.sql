DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'opes_runtime') THEN
    CREATE ROLE opes_runtime LOGIN PASSWORD 'opes_runtime' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
  END IF;
END
$$;

ALTER ROLE opes_runtime WITH LOGIN PASSWORD 'opes_runtime' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;

GRANT CONNECT ON DATABASE opes TO opes_runtime;
GRANT USAGE ON SCHEMA opes TO opes_runtime;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA opes TO opes_runtime;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA opes TO opes_runtime;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA opes TO opes_runtime;
